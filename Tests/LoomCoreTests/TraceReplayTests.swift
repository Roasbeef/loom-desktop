import XCTest
import LoomKit
@testable import LoomCore

/// Replays frames recorded from a real loomd (`make record`) through the production lane and conversation.
///
/// A trace holds what one session lane sent and received, with the time of each frame. The replay
/// resubmits the recorded mutations in order, so the lane allocates the same wire ids, and feeds the
/// recorded replies and pushes back at their recorded times. The clean replay is the reference: the
/// conversation it ends with must show the durable chain with nothing left drawn as live. The same
/// frames replayed under each fault of the session model must end with the same rows.
final class TraceReplayTests: XCTestCase {
    struct Line {
        let direction: String
        let time: Int
        let frame: String
    }

    /// The traces recorded under `Traces/`, by name.
    static func traces() throws -> [(name: String, lines: [Line])] {
        let directory = URL(fileURLWithPath: #filePath).deletingLastPathComponent().appendingPathComponent("Traces")
        let names = try FileManager.default.contentsOfDirectory(atPath: directory.path).filter { $0.hasSuffix(".jsonl") }.sorted()
        return try names.map { name in
            let text = try String(contentsOf: directory.appendingPathComponent(name), encoding: .utf8)
            let lines = try text.split(separator: "\n").map { raw -> Line in
                let value = try JSONValue.parse(Data(raw.utf8))
                return Line(direction: value["d"]?.string ?? "", time: value["t"]?.int ?? 0, frame: value["f"]?.string ?? "")
            }
            return (String(name.dropLast(".jsonl".count)), lines)
        }
    }

    /// The commands the person's side issued. Every other transmitted frame is the lane's own and is
    /// regenerated by the lane from what it receives.
    static let mutations: Set<String> = ["prompt", "steer", "abort", "approve", "deny"]

    enum Fault: String, CaseIterable {
        case none, duplicatePushes, swapPushes, dropStreams
    }

    struct Outcome: Equatable {
        var rows: [String]
        var streams: [String]
    }

    /// Whether a received frame is a push, which carries no `reply_to`.
    static func isPush(_ frame: String) -> Bool {
        guard let value = try? JSONValue.parse(Data(frame.utf8)) else { return false }
        return value["reply_to"] == nil
    }

    static func event(_ frame: String) -> String? {
        (try? JSONValue.parse(Data(frame.utf8)))?["event"]?.string
    }

    /// Applies a fault to the received frames. A reply is never touched: the lane's correlation is the
    /// socket's, and the session model injects its faults on the same boundary.
    static func perturb(_ lines: [Line], fault: Fault) -> [Line] {
        switch fault {
        case .none:
            return lines
        case .duplicatePushes:
            return lines.flatMap { line -> [Line] in
                line.direction == "rx" && isPush(line.frame) && event(line.frame) == "stream_delta" ? [line, line] : [line]
            }
        case .swapPushes:
            var out = lines
            var index = 0
            while index + 1 < out.count {
                if out[index].direction == "rx", out[index + 1].direction == "rx", isPush(out[index].frame), isPush(out[index + 1].frame),
                   event(out[index].frame) == "stream_delta", event(out[index + 1].frame) == "stream_delta" {
                    out.swapAt(index, index + 1)
                    index += 1
                }
                index += 1
            }
            return out
        case .dropStreams:
            return lines.filter { !($0.direction == "rx" && isPush($0.frame) && event($0.frame) == "stream_delta") }
        }
    }

    /// A row's content as text, with JSON in the serializer's fixed key order. `String(describing:)` of a
    /// dictionary changes from one process to the next, which would make the comparison flaky.
    static func label(_ kind: TranscriptRow.Kind) -> String {
        switch kind {
        case .tool(let name, let arguments, let result, let isError):
            return "tool \(name) \(Frames.text(arguments)) \(result ?? "-") \(isError)"
        default:
            return "\(kind)"
        }
    }

    /// Runs the lines through a fresh lane and conversation and reports what is drawn at the end.
    static func replay(_ lines: [Line]) -> Outcome {
        // The session id is the one the recorded subscribe named.
        let sessionID = lines.lazy.compactMap { line -> String? in
            guard line.direction == "tx", let value = try? JSONValue.parse(Data(line.frame.utf8)), value["cmd"]?.string == "subscribe" else { return nil }
            return value["body"]?["session"]?.string
        }.first ?? "unknown"
        var lane = Lane.start(sessionID: sessionID, admission: .daemonDecides, now: 0)
        var conversation = Conversation(sessionID: sessionID)
        _ = lane.takeOutputs()

        func fold(_ updates: [Lane.Update], at now: Int) {
            for update in updates {
                switch update {
                case .cut(_, let cut, _): conversation.apply(cut: cut)
                case .pushed(let frame): conversation.apply(push: frame, now: now)
                default: break
                }
            }
            _ = lane.takeOutputs()
        }

        for line in lines {
            if line.direction == "tx" {
                guard let value = try? JSONValue.parse(Data(line.frame.utf8)), let name = value["cmd"]?.string, mutations.contains(name) else { continue }
                fold(lane.submit(Lane.Command(name, body: value["body"] ?? .object([:]), kind: .mutation), now: line.time).updates, at: line.time)
            } else {
                fold(lane.tick(now: line.time), at: line.time)
                fold(lane.receive(line.frame, now: line.time), at: line.time)
            }
        }
        let rows = conversation.rows(strand: "main").map { "\($0.id)|\(Self.label($0.kind))" }
        let streams = conversation.streams.keys.sorted().map { "\($0)" }
        return Outcome(rows: rows, streams: streams)
    }

    func testEveryTraceEndsWithTheDurableChainAndNothingLive() throws {
        let traces = try Self.traces()
        XCTAssertFalse(traces.isEmpty, "no traces recorded under Tests/LoomCoreTests/Traces")
        for trace in traces {
            let outcome = Self.replay(trace.lines)
            XCTAssertFalse(outcome.rows.isEmpty, "\(trace.name) drew no rows")
            XCTAssertEqual(outcome.streams, [], "\(trace.name) left a stream drawn after the session went idle")
            XCTAssertEqual(Set(outcome.rows).count, outcome.rows.count, "\(trace.name) drew a row twice")
        }
    }

    func testEveryFaultEndsWithTheSameRowsAsTheCleanReplay() throws {
        for trace in try Self.traces() {
            let reference = Self.replay(trace.lines)
            for fault in Fault.allCases where fault != .none {
                let outcome = Self.replay(Self.perturb(trace.lines, fault: fault))
                XCTAssertEqual(outcome, reference, "\(trace.name) under \(fault.rawValue) differs from the clean replay")
            }
        }
    }
}
